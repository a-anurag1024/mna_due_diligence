import json
from langchain_openai import ChatOpenAI
from langchain_core.messages import AIMessage, HumanMessage

from .eval_prompt import PARTY_WISE_EVALUATOR_PROMPT
from .report_card import PartyWiseEvalResult


llm = ChatOpenAI(model="gpt-4.1-mini")


def evaluate_agent_output(generated_risk_report: str,
                          ground_truth_data: dict) -> PartyWiseEvalResult:
    """
    Evaluates the generated risk report against ground truth data for a specific party and risk category.
    
    Args:
        generated_risk_report (str): The risk report generated by the Legal Analyst Agent.
        ground_truth_data (dict): The ground truth data containing clauses of files with the expected risk category.
        
    Returns:
        PartyWiseEvalResult: Structured evaluation result.
    """
    # Prepare the prompt
    user_content = PARTY_WISE_EVALUATOR_PROMPT.format(
        generated_report=generated_risk_report,
        ground_truth=json.dumps(ground_truth_data, indent=1)
    )
    
    # Invoke the LLM
    eval_result: PartyWiseEvalResult = llm.with_structured_output(PartyWiseEvalResult).invoke([
        HumanMessage(content=user_content)
    ])
    
    return eval_result